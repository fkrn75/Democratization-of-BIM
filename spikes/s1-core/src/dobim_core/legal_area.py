def rule_fits(rule: str, target: str, effect: str) -> bool:
    """근거 코드와 대상·효과가 맞는가. manual 은 대상마다 쓸 수 있는 효과(용적률 제외는 바닥면적만, 노대는 근거 코드로만)."""
    if rule not in RULES:
        return False
    if rule == MANUAL:
        return target in TARGETS and effect in ("add", "exclude", "far") and (effect != "far" or target == "floor")
    t, e, _ = RULES[rule]
    return t == target and e == effect


def area2(poly) -> float:
    """부호 있는 면적의 2배(양수 = 반시계)."""
    n = len(poly)
    return sum(poly[i][0] * poly[(i + 1) % n][1] - poly[(i + 1) % n][0] * poly[i][1] for i in range(n))


def balcony_counted(area_mm2: float, contact_length: float) -> float:
    """3호나목: 노대등 면적에서 접한 가장 긴 외벽 길이 x 1.5m 를 뺀 산입 면적(mm2, 0 미만이면 0)."""
    return max(0.0, area_mm2 - contact_length * BALCONY_DEPTH)


def is_basement(elev: float, height: float | None, ground: float) -> bool | None:
    """법 2조1항5호 지하층 판정(지표면 수평 가정). 높이를 모르면(맨 위 레벨) 바닥이 지표면 아래일 때 None(판정 못 함)."""
    if elev >= ground:
        return False
    if height is None or height <= 0:
        return None
    return (ground - elev) >= height / 2.0


def counts_for_building(elev: float, height: float | None, ground: float) -> bool:
    """2호다목1) 을 층 단위로: 그 층 윗면(다음 레벨)이 지표면 위 1m 를 넘거나, 높이를 모르면 바닥이 지표면 이상인 층만 건축면적에 넣는다."""
    if height is None or height <= 0:
        return elev >= ground
    return elev + height > ground + ABOVE_GROUND_MIN


def ratio_pct(num_m2: float, den_m2: float) -> float | None:
    return round(num_m2 / den_m2 * 100.0, 2) if den_m2 > 0 else None
